#!/usr/bin/env python3
"""Audit a WPF restyle against a fixed Git revision, without building Windows UI.

Run from any directory:
    python3 tools/check-ui-contracts.py

This is a review aid, not a UI test. It checks that the redesigned views retain
their functional XAML contracts and that the excluded POS has identical bytes.
Layout, typography, colors, static display labels, and column presentation may
change. It never changes files and always reads the old files from Git objects.
"""

from __future__ import annotations

import argparse
from collections import Counter
from dataclasses import dataclass
import hashlib
from pathlib import Path
import re
import subprocess
import sys
import xml.etree.ElementTree as ET


DEFAULT_BASELINE = "68ff9f1"
VIEWS = "src/PharmacyERP.WPF/Views/"
APP = "src/PharmacyERP.WPF/App.xaml"
XAML_NS = "http://schemas.microsoft.com/winfx/2006/xaml"
THEME_SUFFIX = "Themes/WorkspaceTheme.xaml"

# These bindings describe appearance rather than the values/commands exposed by
# a view. All other Binding/MultiBinding markup is retained, including bindings
# on nested Runs and setters for enabled/visible state.
VISUAL_PROPERTIES = {
    "Style", "Template", "ControlTemplate", "ItemContainerStyle", "RowStyle",
    "CellStyle", "ColumnHeaderStyle", "AlternationIndex", "Background",
    "Foreground", "BorderBrush", "Fill", "Stroke", "Color", "Opacity",
    "Width", "Height", "MinWidth", "MinHeight", "MaxWidth", "MaxHeight",
    "ActualWidth", "ActualHeight", "Margin", "Padding", "FontFamily",
    "FontSize", "FontWeight", "FontStyle", "FontStretch", "CornerRadius",
    "HorizontalAlignment", "VerticalAlignment", "HorizontalContentAlignment",
    "VerticalContentAlignment", "TextAlignment", "TextWrapping", "TextTrimming",
    "BorderThickness", "StrokeThickness", "Effect", "RenderTransform",
    "LayoutTransform", "Cursor", "Grid.Row", "Grid.Column", "Grid.RowSpan",
    "Grid.ColumnSpan", "Panel.ZIndex", "SnapsToDevicePixels", "UseLayoutRounding",
}

# Values that affect user input or data selection even when they are not bound.
# Pure labels (Content/Header/Text literals) deliberately do not belong here.
FUNCTIONAL_LITERALS = {
    "DisplayMemberPath", "SelectedValuePath", "TextSearch.TextPath",
    "IsEditable", "IsReadOnly", "IsTextSearchEnabled", "AcceptsReturn",
    "AcceptsTab", "MaxLength", "IsDefault", "IsCancel", "SelectionMode",
    "SelectionUnit", "AutoGenerateColumns", "CanUserAddRows", "CanUserDeleteRows",
    "CanUserSortColumns", "IsEnabled", "IsTabStop", "GroupName", "CheckBox.IsChecked",
}

KNOWN_EVENTS = {
    "Click", "Loaded", "Unloaded", "Closing", "Closed", "Activated",
    "Deactivated", "Initialized", "SourceInitialized", "ContentRendered",
    "LostFocus", "GotFocus", "LostKeyboardFocus", "GotKeyboardFocus",
    "PreviewLostKeyboardFocus", "PreviewGotKeyboardFocus", "TextInput",
    "PreviewTextInput", "Drop", "DragEnter", "DragLeave", "DragOver",
    "PreviewDrop", "RequestBringIntoView", "ScrollChanged", "Checked",
    "Unchecked", "Indeterminate", "Expanded", "Collapsed", "BeginningEdit",
    "CellEditEnding", "RowEditEnding", "AddingNewItem", "AutoGeneratingColumn",
    "AutoGeneratedColumns", "Sorting", "Executing", "Executed", "CanExecute",
}
EVENT_SUFFIX = re.compile(
    r"(?:Changed|Click|Clicked|DoubleClick|KeyDown|KeyUp|MouseDown|MouseUp|"
    r"MouseMove|MouseEnter|MouseLeave|MouseWheel|TouchDown|TouchUp|TouchMove)$"
)
BINDING_MARKUP = re.compile(r"\{(?:Binding|MultiBinding|PriorityBinding)(?:\s|\})")


def local(name: str) -> str:
    return name.rsplit("}", 1)[-1]


def normalize(value: str) -> str:
    """Ignore markup formatting, retaining paths, converters and validation flags."""
    value = re.sub(r"\s+", " ", value).strip()
    return re.sub(r"\s*([,=])\s*", r"\1", value)


def git(repo: Path, *args: str) -> bytes:
    return subprocess.check_output(["git", "-C", str(repo), *args], stderr=subprocess.PIPE)


def old_bytes(repo: Path, baseline: str, path: str) -> bytes:
    return git(repo, "show", f"{baseline}:{path}")


def git_paths(repo: Path, baseline: str, prefix: str = "src/") -> list[str]:
    return git(repo, "ls-tree", "-r", "--name-only", baseline, prefix).decode().splitlines()


def tree_signature(element: ET.Element) -> tuple:
    """XML semantic signature independent of indentation and attribute order."""
    return (
        element.tag,
        tuple(sorted((key, normalize(value)) for key, value in element.attrib.items())),
        normalize(element.text or ""),
        tuple(tree_signature(child) for child in element),
    )


def effective_property(element: ET.Element, parents: dict[ET.Element, ET.Element], attr: str) -> str:
    if local(element.tag) == "Setter" and attr == "Value":
        return element.get("Property", attr)
    if local(element.tag) in {"Binding", "MultiBinding", "PriorityBinding"}:
        current = element
        while current in parents:
            current = parents[current]
            owner = local(current.tag)
            if "." in owner:
                return owner.split(".", 1)[1]
    return attr


def binding_contracts(root: ET.Element) -> Counter:
    result: Counter = Counter()
    parents = {child: parent for parent in root.iter() for child in parent}
    for element in root.iter():
        tag = local(element.tag)
        # Element-form bindings include their complete tree so MultiBinding
        # formats, constituent paths and validation rules cannot disappear.
        if tag in {"Binding", "MultiBinding", "PriorityBinding"}:
            if element in parents and local(parents[element].tag) in {
                "Binding", "MultiBinding", "PriorityBinding",
            }:
                continue
            prop = effective_property(element, parents, "Binding")
            if prop not in VISUAL_PROPERTIES:
                result[(prop, tree_signature(element))] += 1
        for attr, value in element.attrib.items():
            name = local(attr)
            prop = effective_property(element, parents, name)
            if prop not in VISUAL_PROPERTIES and BINDING_MARKUP.search(value):
                result[(prop, normalize(value))] += 1
    return result


def names(root: ET.Element) -> Counter:
    return Counter(
        value
        for element in root.iter()
        for attr, value in element.attrib.items()
        if attr in {f"{{{XAML_NS}}}Name", "Name"}
    )


def events(root: ET.Element) -> Counter:
    result: Counter = Counter()
    for element in root.iter():
        if local(element.tag) == "EventSetter":
            result[(element.get("Event", ""), element.get("Handler", ""))] += 1
        for attr, value in element.attrib.items():
            attr = local(attr)
            # Namespaced/attached routed event syntax is legal XAML.
            name = attr.rsplit(".", 1)[-1]
            if name in KNOWN_EVENTS or EVENT_SUFFIX.search(name):
                if value and not value.startswith("{"):
                    result[(attr, value)] += 1
    return result


def functional_literals(root: ET.Element) -> Counter:
    return Counter(
        (local(attr), normalize(value))
        for element in root.iter()
        for attr, value in element.attrib.items()
        if local(attr) in FUNCTIONAL_LITERALS and not value.startswith("{")
    )


def input_bindings(root: ET.Element) -> Counter:
    return Counter(
        tree_signature(element)
        for element in root.iter()
        if local(element.tag) in {"KeyBinding", "MouseBinding", "InputBinding", "CommandBinding"}
    )


def validation_metadata(root: ET.Element) -> Counter:
    return Counter(
        tree_signature(element)
        for element in root.iter()
        if "Validation" in local(element.tag)
    )


def columns(root: ET.Element) -> list[list[ET.Element]]:
    # Keep each grid separate, allowing visual column reordering but preventing
    # a field moved to another grid from masking its removal from the first.
    return [
        [column for container in grid if local(container.tag) == "DataGrid.Columns" for column in container]
        for grid in root.iter() if local(grid.tag) == "DataGrid"
    ]


def has_scoped_theme(root: ET.Element) -> bool:
    for resources in root:
        if local(resources.tag) not in {"Window.Resources", "UserControl.Resources"}:
            continue
        for element in resources.iter():
            source = element.get("Source", "").replace("\\", "/")
            if local(element.tag) == "ResourceDictionary" and source.endswith(THEME_SUFFIX):
                return True
    return False


def protected_pos(path: str) -> bool:
    name = path.rsplit("/", 1)[-1]
    return name.startswith("POS") or name.startswith("BarcodeInputBuffer.")


@dataclass
class Finding:
    path: str
    kind: str
    detail: str


def brief(value: object, limit: int = 230) -> str:
    text = str(value)
    return text if len(text) <= limit else text[:limit - 3] + "..."


def audit(repo: Path, baseline: str) -> tuple[list[Finding], int, int]:
    findings: list[Finding] = []
    paths = git_paths(repo, baseline)
    view_paths = [p for p in paths if p.startswith(VIEWS) and p.endswith(".xaml")]
    non_pos = [p for p in view_paths if not protected_pos(p)]

    def fail(path: str, kind: str, detail: str) -> None:
        findings.append(Finding(path, kind, detail))

    def lost(path: str, kind: str, before: Counter, after: Counter) -> None:
        for value, count in (before - after).items():
            fail(path, kind, f"missing {count} occurrence(s): {brief(value)}")

    for path in non_pos:
        current_path = repo / path
        if not current_path.is_file():
            fail(path, "file", "baseline view is missing")
            continue
        try:
            before = ET.fromstring(old_bytes(repo, baseline, path))
            after = ET.fromstring(current_path.read_bytes())
        except ET.ParseError as error:
            fail(path, "XML", str(error))
            continue
        old_class = before.get(f"{{{XAML_NS}}}Class")
        if after.get(f"{{{XAML_NS}}}Class") != old_class:
            fail(path, "x:Class", f"expected {old_class!r}")
        lost(path, "named element", names(before), names(after))
        lost(path, "event handler", events(before), events(after))
        required_bindings = binding_contracts(before)
        current_bindings = binding_contracts(after)
        # v1.1.0 fixes an intentional functional defect: offline update checks
        # must not show "up to date". Retain every other styling-era contract.
        if path == VIEWS + "SystemManagement/UpdateCheckDialog.xaml":
            old_status = ("Visibility", normalize("{Binding Result.IsUpdateAvailable, Converter={StaticResource BoolToVisibilityConverter}, ConverterParameter=Invert}"))
            new_status = ("Visibility", normalize("{Binding IsUpToDate, Converter={StaticResource BoolToVisibilityConverter}}"))
            if required_bindings[old_status] and current_bindings[new_status]:
                required_bindings[new_status] += required_bindings.pop(old_status)
        lost(path, "functional binding", required_bindings, current_bindings)
        lost(path, "input/selection setting", functional_literals(before), functional_literals(after))
        lost(path, "keyboard/command binding", input_bindings(before), input_bindings(after))
        lost(path, "validation metadata", validation_metadata(before), validation_metadata(after))

        before_grids, after_grids = columns(before), columns(after)
        if len(before_grids) != len(after_grids):
            fail(path, "DataGrid", f"grid count changed: {len(before_grids)} -> {len(after_grids)}")
        for index, (old_columns, new_columns) in enumerate(zip(before_grids, after_grids), 1):
            if len(old_columns) != len(new_columns):
                fail(path, "DataGrid columns", f"grid {index}: {len(old_columns)} -> {len(new_columns)} columns")
            old_fields = Counter(tuple(sorted(binding_contracts(c).items(), key=repr)) for c in old_columns)
            new_fields = Counter(tuple(sorted(binding_contracts(c).items(), key=repr)) for c in new_columns)
            lost(path, f"DataGrid {index} column bindings", old_fields, new_fields)

        if not has_scoped_theme(after):
            fail(path, "theme scope", "root Window/UserControl resources must merge Themes/WorkspaceTheme.xaml locally")

        # This opt-out prevents the RTL window from reflecting the label image.
        # The printer itself is independent, so successful physical printing
        # would not catch a regression of the on-screen preview.
        for old_element in before.iter():
            if old_element.get(f"{{{XAML_NS}}}Name") != "PreviewHost":
                continue
            preview = next((element for element in after.iter() if element.get(f"{{{XAML_NS}}}Name") == "PreviewHost"), None)
            if preview is None or preview.get("FlowDirection") != "LeftToRight":
                fail(path, "label preview", "PreviewHost must explicitly retain FlowDirection=LeftToRight")

    protected = [p for p in paths if protected_pos(p)]
    for path in protected:
        current = repo / path
        if not current.is_file():
            fail(path, "POS isolation", "protected POS source is missing")
        elif hashlib.sha256(old_bytes(repo, baseline, path)).digest() != hashlib.sha256(current.read_bytes()).digest():
            fail(path, "POS isolation", f"file bytes differ from {baseline}")
    for current in (repo / "src").rglob("*"):
        if not current.is_file() or any(part in {"bin", "obj"} for part in current.parts):
            continue
        path = current.relative_to(repo).as_posix()
        if protected_pos(path) and path not in protected:
            fail(path, "POS isolation", "new POS source falls outside the authorized restyle")

    app_path = repo / APP
    try:
        before_app = ET.fromstring(old_bytes(repo, baseline, APP))
        after_app = ET.fromstring(app_path.read_bytes())
        for element in after_app.iter():
            if "WorkspaceTheme" in element.get("Source", ""):
                fail(APP, "global theme", "WorkspaceTheme must be scoped to non-POS views, never App resources")
        def implicit_styles(root: ET.Element) -> Counter:
            return Counter(
                tree_signature(element) for element in root.iter()
                if local(element.tag) == "Style" and f"{{{XAML_NS}}}Key" not in element.attrib
            )
        for style, count in (implicit_styles(after_app) - implicit_styles(before_app)).items():
            fail(APP, "global theme", f"{count} new or changed implicit style(s): {brief(style)}")
    except (ET.ParseError, OSError) as error:
        fail(APP, "XML", str(error))
    return findings, len(non_pos), len(protected)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--baseline", default=DEFAULT_BASELINE, help=f"immutable Git revision (default: {DEFAULT_BASELINE})")
    parser.add_argument("--repo", type=Path, default=Path(__file__).resolve().parents[1], help="repository root")
    args = parser.parse_args()
    try:
        git(args.repo, "rev-parse", "--verify", f"{args.baseline}^{{commit}}")
        findings, count, protected_count = audit(args.repo.resolve(), args.baseline)
    except (OSError, subprocess.CalledProcessError) as error:
        print(f"AUDIT ERROR: {error}", file=sys.stderr)
        if isinstance(error, subprocess.CalledProcessError) and error.stderr:
            print(error.stderr.decode(errors="replace").strip(), file=sys.stderr)
        return 2
    print(f"Baseline: {args.baseline}; non-POS views: {count}; protected POS sources: {protected_count}")
    for finding in findings:
        print(f"FAIL {finding.path} [{finding.kind}] {finding.detail}")
    if findings:
        print(f"UI contract audit FAILED: {len(findings)} finding(s).")
        return 1
    print("UI contract audit PASSED: functional XAML retained, themes scoped, POS unchanged.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
